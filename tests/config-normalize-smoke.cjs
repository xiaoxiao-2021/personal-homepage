'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');

const renderer = fs.readFileSync(path.resolve(__dirname, '../src/renderer.js'), 'utf8');
const setup = renderer.slice(0, renderer.indexOf('const taskData ='));
const normalizer = renderer.match(/function validConfig\(config\)[\s\S]*?(?=function current\(\))/)?.[0];
assert.ok(normalizer, 'renderer normalizer source is present');
const context = { URLSearchParams, location: { search: '' }, Math, JSON };
vm.createContext(context);
vm.runInContext(`${setup}\n${normalizer}\nconst legacy=JSON.parse(JSON.stringify(defaults));for(const scene of SCENES){delete legacy.scenes[scene].layout.heights;delete legacy.scenes[scene].layout.entrySize;delete legacy.scenes[scene].layout.spacing;}legacy.theme='peach';legacy.appearance.wallpaper='C:\\\\synthetic\\\\wallpaper.png';legacy.didaListIds={clinical:'list-synthetic'};legacy.library.synthetic={name:'Keep me'};legacy.scenes['🔬 科研'].apps.push('synthetic');legacy.scenes['总览'].layout.order=['apps','apps'];legacy.scenes['总览'].layout.heights={tasks:'invalid'};globalThis.result=JSON.parse(JSON.stringify(normalize(legacy)));`, context);

const result = context.result;
assert.equal(result.theme, 'peach');
assert.equal(result.appearance.renderQuality, 'smooth');
assert.equal(result.appearance.wallpaper, 'C:\\synthetic\\wallpaper.png');
assert.equal(result.didaListIds.clinical, 'list-synthetic');
assert.equal(result.library.synthetic.name, 'Keep me');
assert(result.scenes['🔬 科研'].apps.includes('synthetic'));
assert.deepEqual(result.scenes['总览'].layout.order, ['tasks', 'apps', 'side']);
assert.equal(result.scenes['总览'].layout.heights.tasks, 'medium');
assert.equal(result.scenes['🏥 临床'].layout.entrySize, 'medium');
assert.equal(result.scenes['📚 学习'].layout.spacing, 'comfortable');
assert.equal(result.scenes['总览'].layout.entryStyle, 'tiles');
assert.equal(result.scenes['总览'].layout.showUnsetEntries, true);
assert.equal(result.scenes['总览'].layout.heights.apps, 'medium');
assert.equal(result.scenes['🏥 临床'].layout.heights.tasks, 'medium');
assert.equal(result.taskViews['总览'].dates, 'all');
assert.equal(result.taskViews['总览'].inboxProjectId, '');
assert.equal(result.taskViews['🏠 生活'].range, 'scene');
assert.equal(result.taskViews['🏠 生活'].dates, 'all');
const scoped = JSON.parse(JSON.stringify(result));
scoped.taskViews['🏠 生活'] = { range: 'inbox', dates: 'today', inboxProjectId: 'life-list' };
vm.runInContext(`globalThis.scopedResult=JSON.parse(JSON.stringify(normalize(${JSON.stringify(scoped)})))`, context);
assert.deepEqual(context.scopedResult.taskViews['🏠 生活'], { range: 'inbox', dates: 'today', inboxProjectId: 'life-list' });
const modern = JSON.parse(JSON.stringify(result));
modern.scenes['总览'].layout.heights.tasks = 'content';
modern.appearance.renderQuality = 'full';
modern.scenes['总览'].layout.entryStyle = 'compact';
modern.scenes['总览'].layout.showUnsetEntries = false;
modern.scenes['🔬 科研'].layout.heights.apps = 'tall';
vm.runInContext(`globalThis.modernResult=JSON.parse(JSON.stringify(normalize(${JSON.stringify(modern)})))`, context);
assert.equal(context.modernResult.scenes['总览'].layout.heights.tasks, 'content');
assert.equal(context.modernResult.appearance.renderQuality, 'full');
assert.equal(context.modernResult.scenes['总览'].layout.entryStyle, 'compact');
assert.equal(context.modernResult.scenes['总览'].layout.showUnsetEntries, false);
assert.equal(context.modernResult.scenes['🔬 科研'].layout.heights.apps, 'tall');
assert.equal(context.modernResult.scenes['🏥 临床'].layout.entryStyle, 'tiles');
console.log('config normalization checks passed: legacy card heights remain medium; new per-scene height/style/visibility fields default safely and persist independently');
